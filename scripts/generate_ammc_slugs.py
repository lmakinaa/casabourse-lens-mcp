#!/usr/bin/env python3
"""Generate AMMC issuer slug map from issuer_symbols.json.

This script merges the existing `trading_tools/mappings/ammc_issuer_slugs.json`
with slugs inferred from `ingestion/mappings/issuer_symbols.json`.

Usage: ./scripts/generate_ammc_slugs.py
"""
from __future__ import annotations

import json
import unicodedata
from pathlib import Path


ROOT = Path(__file__).resolve().parent.parent
ISSUER_MAP = ROOT / "ingestion" / "mappings" / "issuer_symbols.json"
SLUG_MAP = ROOT / "trading_tools" / "mappings" / "ammc_issuer_slugs.json"


def slugify(text: str) -> str:
    folded = unicodedata.normalize("NFKD", text or "")
    no_marks = "".join(ch for ch in folded if not unicodedata.combining(ch))
    lowered = no_marks.lower()
    lowered = __import__("re").sub(r"[^a-z0-9]+", "-", lowered).strip("-")
    lowered = __import__("re").sub(r"-+", "-", lowered)
    return lowered


def main() -> None:
    if not ISSUER_MAP.exists():
        raise SystemExit(f"missing issuer map: {ISSUER_MAP}")

    issuer_raw = json.loads(ISSUER_MAP.read_text(encoding="utf-8"))
    # existing slug map (if present)
    existing = {}
    if SLUG_MAP.exists():
        try:
            existing = json.loads(SLUG_MAP.read_text(encoding="utf-8"))
        except Exception:
            existing = {}

    # Build a canonical representative name per symbol by taking the
    # first encountered name in issuer_symbols.json for each symbol.
    symbol_to_name: dict[str, str] = {}
    for name, symbol in issuer_raw.items():
        if str(name).startswith("_"):
            continue
        sym = str(symbol).strip().upper()
        if not sym or sym in symbol_to_name:
            continue
        symbol_to_name[sym] = str(name).strip()

    merged = {}
    # Preserve comment if present
    if isinstance(existing, dict):
        for k, v in existing.items():
            if str(k).startswith("_"):
                merged[k] = v

    # Add existing explicit mappings first
    if isinstance(existing, dict):
        for k, v in existing.items():
            if not str(k).startswith("_"):
                merged[str(k).upper()] = str(v).strip().lower().strip("/")

    # Infer and add missing symbols
    for sym, name in sorted(symbol_to_name.items()):
        if sym in merged:
            continue
        slug = slugify(name)
        if slug:
            merged[sym] = slug

    # Write back sorted mapping (keep comment first)
    out = {}
    if "_comment" in merged:
        out["_comment"] = merged.pop("_comment")
    else:
        out["_comment"] = "Static AMMC issuer slug mapping (symbol -> slug). Generated by scripts/generate_ammc_slugs.py"

    for sym in sorted(k for k in merged.keys() if not str(k).startswith("_")):
        out[sym] = merged[sym]

    SLUG_MAP.write_text(json.dumps(out, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"wrote {SLUG_MAP} with {len(out)-1} symbols")


if __name__ == "__main__":
    main()
